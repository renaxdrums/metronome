import assert from 'node:assert/strict';
import {renderWarpInWorker} from '../audio-lab/dsp/warp-client.mjs';
const data=new Float32Array(16000),original=data.slice();
const buffer={length:data.length,numberOfChannels:1,sampleRate:16000,getChannelData:()=>data};
const timeline={outputDurationSeconds:2,sourceDurationSeconds:1,segments:[{startTick:0,endTick:3840,sourceStartSeconds:0,sourceEndSeconds:1,outputStartSeconds:0,outputEndSeconds:2}]};
let terminated=0,posted,thread;
const workerFactory=()=>{thread={postMessage:(message,transfer)=>{posted={message,transfer};},terminate:()=>terminated++};return thread;};
const active=renderWarpInWorker({buffer,timeline,workerFactory});
assert.equal(posted.message.config.channels[0].length,16000);
assert.notEqual(posted.message.config.channels[0].buffer,data.buffer);
assert.equal(posted.transfer.length,1);
thread.onmessage({data:{id:1,type:'done',rendered:{channels:[new Float32Array(32000)],sampleRate:16000}}});
assert.equal((await active).channels[0].length,32000);
assert.equal(terminated,1);assert.deepEqual(data,original);
const ctl=new AbortController();
const pending=renderWarpInWorker({buffer,timeline,workerFactory,signal:ctl.signal});
ctl.abort();
await assert.rejects(pending,e=>e.code==='CANCELLED');
assert.equal(terminated,2);
assert.throws(()=>renderWarpInWorker({buffer,timeline,maxOutputBytes:2000}),e=>e.code==='MEMORY_PRESSURE');
const interrupted=renderWarpInWorker({buffer,timeline,workerFactory});
thread.onmessage({data:{id:1,type:'error',code:'TOO_SHORT',message:'test'}});
await assert.rejects(interrupted,e=>e.code==='TOO_SHORT');
assert.equal(terminated,3);
console.log('Audio Lab Warp Worker: PCM copy, abort, failure cleanup and memory guards OK');
